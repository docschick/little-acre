// Convert a public-page inventory into factual, source-linked catalog data.
// Descriptions, prices, reviews, and images are deliberately not republished.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';

const [listingFile,detailsFile,collectionsFile]=process.argv.slice(2);
assert.ok(listingFile&&detailsFile&&collectionsFile,'Usage: node scripts/build-burpee-catalog.mjs listing.json details.json collections.json');
const listing=JSON.parse(readFileSync(listingFile,'utf8'));
const details=JSON.parse(readFileSync(detailsFile,'utf8'));
const collections=JSON.parse(readFileSync(collectionsFile,'utf8'));
const byUrl=new Map(details.map(row=>[row.url,row]));
assert.equal(new Set(listing.map(row=>row.url)).size,listing.length,'Listing contains duplicate URLs');
const entries=[],excluded=[];
for(const item of listing){
  const row=byUrl.get(item.url);
  assert.ok(row?.title&&Object.keys(row.attributes).length,`Missing product details: ${item.url}`);
  const sourceCategory=row.breadcrumbs[0]?.name;
  const sourceCrop=row.breadcrumbs.at(-1)?.name;
  let category=sourceCategory==='Fruits'&&['Watermelon','Melon','Cantaloupe'].includes(sourceCrop)?'Vegetables':sourceCategory;
  if(!['Vegetables','Herbs','Flowers','Perennials','Fruits'].includes(category)){
    const memberships=collections.filter(c=>row.breadcrumbs.some(b=>b.url===c.url));
    category=memberships.find(c=>c.category==='Herbs')?.category||memberships.find(c=>c.category==='Vegetables')?.category||memberships.find(c=>c.category==='Perennials'&&row.attributes.Lifecycle==='Perennial')?.category||memberships[0]?.category||category;
  }
  if(!['Vegetables','Herbs','Flowers','Perennials'].includes(category)){
    excluded.push({title:row.title,url:row.url,category:category||'Unclassified'});
    continue;
  }
  assert.match(row.url,/^https:\/\/www\.burpee\.com\/products\/[a-z0-9-]+$/);
  const attributes=Object.fromEntries(Object.entries(row.attributes).filter(([key,value])=>key&&typeof value==='string'&&value.trim()));
  if(/\bF1 Hybrid\s*$/.test(row.description||''))attributes['Seed type']='F1 hybrid';
  else if(/^\s*Heirloom\b/i.test(row.description||''))attributes['Seed type']='Heirloom';
  // Some product breadcrumbs say only “Annuals”; the listing link carries the variety name.
  assert.ok(typeof item.title==='string'&&item.title.trim(),`Missing listing title: ${item.url}`);
  entries.push({slug:new URL(row.url).pathname.split('/').pop(),title:item.title,category,...(category!==sourceCategory?{sourceCategory}:{}),crop:sourceCrop||category,attributes});
}
entries.sort((a,b)=>a.slug.localeCompare(b.slug));
const checkedOn='2026-11-09';
const summary={checkedOn,listingUrl:'https://www.burpee.com/collections/all-seeds?filter.v.m.burpee.propagule-type=Seed',listedSeedProducts:listing.length,included:entries.length,categories:Object.fromEntries(['Vegetables','Herbs','Flowers','Perennials'].map(c=>[c,entries.filter(row=>row.category===c).length])),excluded};
const lines=entries.map(entry=>'  '+JSON.stringify(entry));
writeFileSync(new URL('../burpee-seed-data.js',import.meta.url),`// Factual product attributes checked ${checkedOn}. Generated by scripts/build-burpee-catalog.mjs.\n// No descriptions, prices, images, or planting records are included.\nexport const burpeeCatalogSummary=${JSON.stringify(summary,null,2)};\nexport const burpeeCropGroups=${JSON.stringify([...new Set(collections.map(c=>c.name))].sort())};\nexport const burpeeSeedData=[\n${lines.join(',\n')}\n];\n`);
console.log(JSON.stringify(summary,null,2));
